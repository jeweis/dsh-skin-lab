/**
 * Inline the prepared JPEGs into a source module.
 *
 * A client bundle is served as a single script, and there is no documented route
 * for a plugin to fetch a sibling file, so a built-in background has to travel
 * inside the bundle as a `data:` URL. That is also exactly what a user-uploaded
 * image becomes, so the model has one representation for both.
 *
 * The artwork is **pairwise**: every theme ships one image per colour scheme, and
 * the runtime picks the member that matches the scheme in force. Both members are
 * required — a theme with only one image is the defect this shape exists to make
 * impossible, so a half-populated pair is a build failure rather than a fallback.
 *
 * `src/assets.js` is generated output and committed, like the artwork it wraps:
 * the sources of truth are `assets/*.jpg`, produced by
 * `scripts/prepare-assets.py`.
 *
 * Usage: node scripts/embed-assets.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const assetsDir = join(root, 'assets')
const SCHEMES = ['light', 'dark']

const files = readdirSync(assetsDir).filter((file) => file.endsWith('.jpg')).sort()
if (files.length === 0) throw new Error('embed-assets: no assets/*.jpg found — run scripts/prepare-assets.py first')

// The measured lightness travels with the artwork, because the plugin cannot read a
// pixel of it at runtime and the scrim strength depends on it.
const lightnessPath = join(assetsDir, 'lightness.json')
if (!existsSync(lightnessPath)) {
  throw new Error('embed-assets: assets/lightness.json is missing — re-run scripts/prepare-assets.py')
}
const lightness = JSON.parse(readFileSync(lightnessPath, 'utf8'))

/** @type {Record<string, Record<string, string>>} */
const sources = {}
/** @type {Record<string, Record<string, { mean: number, p05: number, p95: number }>>} */
const measured = {}

let total = 0
for (const file of files) {
  const stem = file.replace(/\.jpg$/, '')
  const cut = stem.lastIndexOf('-')
  const key = cut > 0 ? stem.slice(0, cut) : ''
  const scheme = cut > 0 ? stem.slice(cut + 1) : ''
  if (key === '' || !SCHEMES.includes(scheme)) {
    throw new Error(`embed-assets: "${file}" is not named <theme>-<${SCHEMES.join('|')}>`)
  }
  const value = lightness[stem]
  if (value === null || typeof value !== 'object') {
    throw new Error(`embed-assets: lightness.json has no measurement object for "${stem}" — re-run scripts/prepare-assets.py`)
  }
  for (const field of ['mean', 'p05', 'p95']) {
    if (typeof value[field] !== 'number') throw new Error(`embed-assets: lightness.json entry "${stem}" has no ${field}`)
  }
  const bytes = readFileSync(join(assetsDir, file))
  total += bytes.length
  // JPEG is what the sanitizer's `data:image/` allowance expects.
  ;(sources[key] ??= {})[scheme] = `data:image/jpeg;base64,${bytes.toString('base64')}`
  ;(measured[key] ??= {})[scheme] = { mean: value.mean, p05: value.p05, p95: value.p95 }
}

const keys = Object.keys(sources).sort()
for (const key of keys) {
  const missing = SCHEMES.filter((scheme) => !(scheme in sources[key]))
  if (missing.length > 0) {
    throw new Error(`embed-assets: theme "${key}" has no ${missing.join(', ')} artwork — every theme needs both, or its look is a washed-out version of the other scheme's image`)
  }
}

/** @param {Record<string, unknown>} record */
const render = (record) => keys.map((key) => {
  const inner = SCHEMES.map((scheme) => `    ${JSON.stringify(scheme)}: ${JSON.stringify(record[key][scheme])},`).join('\n')
  return `  ${JSON.stringify(key)}: {\n${inner}\n  },`
}).join('\n')

/** @param {Record<string, Record<string, { mean: number, p05: number, p95: number }>>} record */
const renderLightness = (record) => keys.map((key) => {
  const inner = SCHEMES.map((scheme) => {
    const stats = record[key][scheme]
    return `    ${JSON.stringify(scheme)}: { mean: ${String(stats.mean)}, p05: ${String(stats.p05)}, p95: ${String(stats.p95)} },`
  }).join('\n')
  return `  ${JSON.stringify(key)}: {\n${inner}\n  },`
}).join('\n')

const module = `/**
 * GENERATED by scripts/embed-assets.mjs — do not edit by hand.
 *
 * Built-in theme backgrounds. Every key is a theme id and every member is one
 * colour scheme's own artwork, so the paint picks a member instead of scrimming
 * one image into a scheme it was not drawn for. Edit the artwork, re-run
 * \`scripts/prepare-assets.py\` then this script.
 *
 * @type {Record<string, { light: string, dark: string }>}
 */
export const embeddedBackgrounds = {
${render(sources)}
}

/**
 * Lightness statistics of each built-in artwork, measured by
 * \`scripts/prepare-assets.py\` after the same crop and resize that produced the JPEG.
 *
 * \`mean\` drives the automatic scrim. It is zero for every built-in theme in its own
 * scheme — that is what the pairing is for — and non-zero only for a single image the
 * user supplied, where there is no counterpart to switch to.
 *
 * \`p05\` / \`p95\` bound legibility instead of guessing at it. The two schemes fail in
 * opposite directions: under a light interface the label is near-black, so the darkest
 * region of the artwork is what can swallow it, and under a dark interface the lightest
 * region is. The verification step composites those two tails against each theme's own
 * label colour and requires WCAG AA, so an over-bright highlight is caught here rather
 * than by a user who cannot read a paragraph.
 *
 * @type {Record<string, { light: { mean: number, p05: number, p95: number }, dark: { mean: number, p05: number, p95: number } }>}
 */
export const embeddedBackgroundLightness = {
${renderLightness(measured)}
}

/** Theme keys available as built-in backgrounds. */
export const embeddedBackgroundKeys = ${JSON.stringify(keys)}
`

const target = join(root, 'src', 'assets.js')
writeFileSync(target, module)
console.log(`embedded ${String(files.length)} backgrounds = ${String(keys.length)} theme pairs (${(total / 1024).toFixed(1)} KB of JPEG) into src/assets.js (${(statSync(target).size / 1024).toFixed(1)} KB)`)
